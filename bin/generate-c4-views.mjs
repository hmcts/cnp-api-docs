#!/usr/bin/env node
// Generates c4/views.generated.c4: the landscape plus one overview per product.
//
// Ports the 28 docs/c4/*/workspace.dsl files. Each was ~30 lines of
// `include *` / `exclude idam` / `exclude rpe` / `exclude relationship==bsp->*` /
// `autoLayout` around a single systemContext and container view, so generating
// them keeps the intent and removes the drift. The `exclude idam` / `exclude rpe`
// pair becomes one `exclude element.tag = #ambient`.
//
// Views that carry hand-written actor detail (probate, pcs, nfdiv, darts) are in
// c4/views.c4 and are not generated.

import { readFileSync, writeFileSync } from 'node:fs';

const OUT = 'c4/views.generated.c4';
const HAND_WRITTEN = new Set(['probate', 'pcs', 'nfdiv', 'darts']);

const idOf = (s) => {
  const safe = s.replace(/[^A-Za-z0-9_]/g, '_');
  return /^[0-9]/.test(safe) ? `s_${safe}` : safe;
};
const slugOf = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const quote = (s) => (s ?? '').replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\s+/g, ' ').trim();

const model = JSON.parse(readFileSync('model/model.json', 'utf8'));
const products = Object.values(model.products)
  .filter((g) => g.serviceCount > 0)
  .sort((a, b) => a.name.localeCompare(b.name));

// Products with no dependency to or from another product. Ambient auth is excluded
// from the landscape, so for these there is nothing left to draw.
const ambient = new Set(
  Object.values(model.services).filter((s) => s.ambient).map((s) => s.id),
);
const connected = new Set();
for (const s of Object.values(model.services)) {
  if (!s.product) continue;
  for (const dep of s.dependsOn) {
    if (ambient.has(dep.id)) continue;
    const target = model.services[dep.id];
    if (!target?.product || target.product === s.product) continue;
    connected.add(s.product);
    connected.add(target.product);
  }
}
// Only products that exist in the C4 model, which needs at least one service.
const unconnected = Object.values(model.products)
  .filter((p) => p.serviceCount > 0 && !connected.has(p.name))
  .map((p) => p.name);

const lines = [];
lines.push('// Generated by bin/generate-c4-views.mjs. Do not edit.');
lines.push('// Views with hand-written actor detail are in c4/views.c4.');
lines.push('');
lines.push('views {');
lines.push('');

// Landscape: products and the traffic between them. Excluding ambient auth leaves
// 58 edges over 23 products, which lays out readably top-to-bottom because the
// estate is two-tiered — service teams call down into shared platform.
//
// Products with no cross-product edge at all are excluded: on this view they are
// unconnected boxes, and the products page already lists every one.
lines.push('  view landscape {');
lines.push("    title 'CNP landscape'");
lines.push(
  "    description 'Traffic between products. Authentication and identity are excluded. Click a product to open its own view.'",
);
lines.push('    include');
lines.push('      element.kind = product,');
lines.push('      element.kind = product -> element.kind = product');
lines.push('    exclude');
lines.push('      element.tag = #ambient,');
lines.push(`      ${unconnected.map(idOf).join(',\n      ')}`);
lines.push('    autoLayout TopBottom 60 40');
lines.push('');
lines.push('    style element.tag = #platform {');
lines.push('      color green');
lines.push('    }');
lines.push('  }');
lines.push('');

for (const g of products) {
  const slug = slugOf(g.name);
  if (HAND_WRITTEN.has(slug)) continue;

  // The landscape links each product box to this view, so clicking a box on the
  // landscape opens the product rather than doing nothing.
  lines.push(`  view ${idOf(slug)}_overview of ${idOf(g.name)} {`);
  lines.push(`    title '${quote(g.name)} overview'`);
  lines.push(
    `    description 'Services in ${quote(g.name)} and their immediate neighbours. Authentication and identity are omitted.'`,
  );
  lines.push('    include');
  lines.push('      *,');
  lines.push('      -> * ->');
  lines.push('    exclude');
  lines.push('      element.tag = #ambient');
  lines.push('    autoLayout LeftRight');
  lines.push('  }');
  lines.push('');
}

lines.push('}');
lines.push('');

writeFileSync(OUT, lines.join('\n'));

const generated = products.filter((g) => !HAND_WRITTEN.has(slugOf(g.name))).length;
console.log(`${OUT} written`);
console.log(`  landscape:      1`);
console.log(`  product overviews: ${generated} generated, ${HAND_WRITTEN.size} hand-written`);
