#!/usr/bin/env node
// Generates the LikeC4 model from model.json into c4/generated.c4.
//
// Hand-written views live in c4/views.c4 and are not touched.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const OUT = 'c4/generated.c4';

// LikeC4 identifiers cannot contain hyphens or start with a digit.
const idOf = (s) => {
  const safe = s.replace(/[^A-Za-z0-9_]/g, '_');
  return /^[0-9]/.test(safe) ? `s_${safe}` : safe;
};

// Single-quoted strings in the DSL. Descriptions come from OpenAPI info blocks
// and registry prose written for an HTML page, so strip the markup — the diagram
// renders it literally otherwise.
const quote = (s) =>
  (s ?? '')
    .replace(/<[^>]*>/g, '')
    .replace(/&amp;/g, '&')
    .replace(/&nbsp;/g, ' ')
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\s+/g, ' ')
    .trim();

const model = JSON.parse(readFileSync('model/model.json', 'utf8'));

// Only services that carry architectural meaning: those the registry places in a
// product. The 102 spec-only services have no product or edges, so putting them in a
// diagram would add nodes with no relationships.
const placed = Object.values(model.services).filter((s) => s.product);
const placedIds = new Set(placed.map((s) => s.id));

const byProduct = {};
for (const s of placed) (byProduct[s.product] ??= []).push(s);

const lines = [];
lines.push('// Generated by bin/generate-c4.mjs from model/model.json. Do not edit.');
lines.push('// Hand-written views are in c4/views.c4.');
lines.push('');
lines.push('specification {');
lines.push('  element actor {');
lines.push('    style { shape person }');
lines.push('  }');
lines.push('  element product');
lines.push('  element service');
lines.push('  element frontend {');
lines.push('    style { shape browser }');
lines.push('  }');
// Ambient infrastructure is tagged so views can exclude it in one predicate
// instead of listing idam and rpe by hand, as the Structurizr views did.
lines.push('  tag ambient');
lines.push('  tag broken');
lines.push('}');
lines.push('');
lines.push('model {');

for (const [id, a] of Object.entries(model.actors)) {
  lines.push(`  ${idOf(id)} = actor '${quote(a.name)}' {`);
  if (a.description) lines.push(`    description '${quote(a.description)}'`);
  lines.push('  }');
}
lines.push('');

for (const [productName, members] of Object.entries(byProduct).sort()) {
  const g = model.products[productName];
  lines.push(`  ${idOf(productName)} = product '${quote(productName)}' {`);
  if (g?.info) lines.push(`    description '${quote(g.info).slice(0, 200)}'`);

  for (const s of members.sort((a, b) => a.id.localeCompare(b.id))) {
    const kind = s.type === 'web' ? 'frontend' : 'service';
    const tags = [s.ambient ? '#ambient' : null, s.brokenSpecs > 0 ? '#broken' : null].filter(Boolean);
    lines.push(`    ${idOf(s.id)} = ${kind} '${quote(s.id)}' {`);
    if (tags.length) lines.push(`      ${tags.join(' ')}`);
    if (s.description) lines.push(`      description '${quote(s.description)}'`);
    if (s.repository) lines.push(`      link ${s.repository}`);
    lines.push('    }');
  }
  lines.push('  }');
}
lines.push('');

// Relationships, declared after all elements so order does not matter.
for (const s of placed) {
  for (const dep of s.dependsOn) {
    if (!placedIds.has(dep.id)) continue;
    const label = dep.hard ? 'uses' : 'uses (soft)';
    lines.push(`  ${idOf(s.id)} -> ${idOf(dep.id)} '${label}'`);
  }
}
for (const [id, a] of Object.entries(model.actors)) {
  for (const target of a.uses) {
    if (!placedIds.has(target)) continue;
    lines.push(`  ${idOf(id)} -> ${idOf(target)} 'uses'`);
  }
}
for (const cb of model.callbacks) {
  if (!placedIds.has(cb.from) || !placedIds.has(cb.to)) continue;
  lines.push(`  ${idOf(cb.from)} -> ${idOf(cb.to)} 'callbacks'`);
}

lines.push('}');
lines.push('');

mkdirSync('c4', { recursive: true });
writeFileSync(OUT, `${lines.join('\n')}`);

const edges = lines.filter((l) => l.includes(' -> ')).length;
console.log(`${OUT} written`);
console.log(`  products: ${Object.keys(byProduct).length}`);
console.log(`  services: ${placed.length}`);
console.log(`  actors:   ${Object.keys(model.actors).length}`);
console.log(`  edges:    ${edges}`);
