#!/usr/bin/env node
// Caches ownership data from every catalog-info.yaml in the hmcts org into
// model/catalog-cache.json.
//
// Backstage catalog entities are the only place a spec's owning team is
// recorded, and they live in ~132 other repos. Fetching them during a site build
// would need a token and network access on every run, so a nightly workflow
// refreshes this cache and opens a PR instead. Builds then read a committed file.
//
// Usage:
//   refresh-catalog-cache.mjs                 fetch via the GitHub code search API
//   refresh-catalog-cache.mjs --from-dir DIR   read from a local checkout tree
//
// --from-dir is how this is run against a cft-workspace clone, which already has
// every repo on disk; it needs no token and is much faster.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { parse } from 'yaml';

const OUT = 'model/catalog-cache.json';

// Vendored fixtures and build artifacts carry catalog files that are not real
// entities; counting them would inflate coverage and can produce duplicates.
const EXCLUDE = /node_modules|\/build\/|test-projects|retrofit-reports|bin\/default/;

function fromDir(dir) {
  const out = execFileSync(
    'find',
    [dir, '-name', 'catalog-info.yaml', '-not', '-path', '*/node_modules/*'],
    { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 },
  );
  return out.split('\n').filter((p) => p.trim() && !EXCLUDE.test(p));
}

function readEntity(path) {
  let doc;
  try {
    doc = parse(readFileSync(path, 'utf8'));
  } catch (err) {
    return { path, error: `unparseable: ${err.message}` };
  }
  if (!doc || typeof doc !== 'object') return { path, error: 'empty' };

  const name = doc.metadata?.name;
  const slug = doc.metadata?.annotations?.['github.com/project-slug'];

  // Two repos still contain unrendered scaffolder placeholders; those entities
  // fail Backstage ingestion too, so flag rather than import them.
  if (typeof name === 'string' && name.includes('${{')) {
    return { path, error: 'unrendered template placeholder' };
  }

  return {
    path,
    name,
    repo: typeof slug === 'string' ? slug.replace(/^hmcts\//, '') : undefined,
    kind: doc.kind,
    type: doc.spec?.type,
    lifecycle: doc.spec?.lifecycle,
    owner: doc.spec?.owner,
    system: doc.spec?.system,
    tags: doc.metadata?.tags,
    // Federation targets: once teams declare these, they take precedence over
    // registry.yaml. Zero repos set them today.
    dependsOn: doc.spec?.dependsOn,
    providesApis: doc.spec?.providesApis,
    consumesApis: doc.spec?.consumesApis,
  };
}

function main(argv) {
  const dirIdx = argv.indexOf('--from-dir');
  if (dirIdx === -1 || !argv[dirIdx + 1]) {
    console.error('usage: refresh-catalog-cache.mjs --from-dir <path-to-repo-tree>');
    console.error('(GitHub API mode is not implemented; run against a cft-workspace clone)');
    return 2;
  }

  const paths = fromDir(argv[dirIdx + 1]);
  const entities = {};
  const problems = [];
  let federated = 0;

  for (const path of paths) {
    const e = readEntity(path);
    if (e.error) {
      problems.push({ path: e.path, error: e.error });
      continue;
    }
    const key = e.repo ?? e.name;
    if (!key) {
      problems.push({ path: e.path, error: 'no name or project-slug' });
      continue;
    }
    if (e.dependsOn || e.providesApis || e.consumesApis) federated++;

    // Keep it small: the site only needs ownership and the federation fields.
    entities[key] = {
      name: e.name,
      owner: e.owner,
      lifecycle: e.lifecycle,
      type: e.type,
      ...(e.system ? { system: e.system } : {}),
      ...(e.tags ? { tags: e.tags } : {}),
      ...(e.dependsOn ? { dependsOn: e.dependsOn } : {}),
      ...(e.providesApis ? { providesApis: e.providesApis } : {}),
      ...(e.consumesApis ? { consumesApis: e.consumesApis } : {}),
    };
  }

  mkdirSync('model', { recursive: true });
  writeFileSync(
    OUT,
    `${JSON.stringify(
      {
        note: 'Generated by bin/refresh-catalog-cache.mjs. Do not edit by hand.',
        entityCount: Object.keys(entities).length,
        federatedCount: federated,
        problems,
        entities,
      },
      null,
      2,
    )}\n`,
  );

  const owners = new Set(Object.values(entities).map((e) => e.owner).filter(Boolean));
  console.log(`${OUT} written`);
  console.log(`  entities:  ${Object.keys(entities).length}`);
  console.log(`  owners:    ${owners.size} distinct teams`);
  console.log(`  federated: ${federated} declare dependsOn/providesApis/consumesApis`);
  console.log(`  problems:  ${problems.length}`);
  for (const p of problems) console.log(`    ${p.path}: ${p.error}`);
  return 0;
}

process.exit(main(process.argv.slice(2)));
